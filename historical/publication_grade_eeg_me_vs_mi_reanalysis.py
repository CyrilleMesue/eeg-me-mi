"""## Duration sensitivity analysis

The original workflow compared a flattened representation of the first 60 seconds with one of the full run. Here the scientific unit remains an event-related trial. The sensitivity analysis asks whether training and evaluating on cue events occurring in the first 60 seconds changes unseen-participant performance relative to using all cue events. It uses the same ERD pipeline and the same deterministic participant-fold assignment.

A paired participant-level difference and its bootstrap interval are more informative than comparing the single best classifier from two unrelated random splits.

"""

def paired_bootstrap_difference(frame_a, frame_b, metric, n_bootstrap, seed):
    paired = frame_a[["subject", metric]].merge(
        frame_b[["subject", metric]], on="subject", suffixes=("_a", "_b")
    ).dropna()
    diff = paired[f"{metric}_b"] - paired[f"{metric}_a"]
    rng = np.random.default_rng(seed)
    boot = np.empty(n_bootstrap)
    for i in range(n_bootstrap):
        boot[i] = rng.choice(diff.to_numpy(), size=len(diff), replace=True).mean()
    return {
        "metric": metric,
        "mean_full_minus_first60": diff.mean(),
        "ci_low": np.quantile(boot, 0.025),
        "ci_high": np.quantile(boot, 0.975),
        "wilcoxon_p": wilcoxon(diff).pvalue if np.any(diff != 0) else 1.0,
        "n_subjects": len(diff),
    }


