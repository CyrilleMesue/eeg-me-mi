"""## Optional group-aware permutation test

This test randomly swaps the ME/MI assignment within each participant, preserving participant structure and class balance. It reruns the complete nested selection procedure for every permutation, so it is intentionally disabled by default and computationally expensive. Enable it for the final paper run. A small number such as 20 is useful only to test the code; use the prespecified 1,000 permutations for inference.

"""

def flip_labels_by_subject(y, groups, rng):
    y_perm = y.copy()
    for subject in np.unique(groups):
        idx = groups == subject
        if rng.random() < 0.5:
            y_perm[idx] = 1 - y_perm[idx]
    return y_perm


def nested_group_permutation_test(X, y, groups, metadata, estimator, param_grid, n_permutations):
    observed_result = results["erd"]
    observed = observed_result["subject_metrics"]["balanced_accuracy"].mean()
    rng = np.random.default_rng(CFG.seed)
    null = np.empty(n_permutations)

    for permutation in range(n_permutations):
        y_perm = flip_labels_by_subject(y, groups, rng)
        permuted = run_nested_group_cv(
            f"permutation_{permutation + 1}",
            X, y_perm, groups, metadata, estimator, param_grid,
            verbose=False,
        )
        null[permutation] = permuted["subject_metrics"]["balanced_accuracy"].mean()
        print(f"Permutation {permutation + 1}/{n_permutations}", end="\r")

    p_value = (1 + np.sum(null >= observed)) / (n_permutations + 1)
    return observed, null, p_value


