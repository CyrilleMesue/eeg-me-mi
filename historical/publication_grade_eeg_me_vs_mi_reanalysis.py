def load_run(subject: int, run: int):
    condition, task_family, repetition = RUN_INFO[run]
    files = eegbci.load_data(
        subject,
        runs=[run],
        path=str(DATA_DIR),
        update_path=False,
    )
    if len(files) != 1:
        raise RuntimeError(f"Expected one EDF for subject {subject}, run {run}; got {len(files)}")

    raw = read_raw_edf(files[0], preload=True, verbose=False)
    eegbci.standardize(raw)
    raw.resample(CFG.target_sfreq, npad="auto", verbose=False)
    raw.pick(picks="eeg")
    raw.set_montage("standard_1005", on_missing="raise", verbose=False)
    raw.set_eeg_reference("average", projection=False, verbose=False)
    raw.filter(
        CFG.l_freq,
        CFG.h_freq,
        picks="eeg",
        method="fir",
        phase="zero",
        fir_design="firwin",
        skip_by_annotation="edge",
        verbose=False,
    )

    missing = sorted(set(SENSORIMOTOR_CHANNELS) - set(raw.ch_names))
    if missing:
        raise RuntimeError(f"Missing required channels: {missing}")
    raw.pick(SENSORIMOTOR_CHANNELS)

    events, _ = mne.events_from_annotations(
        raw,
        event_id={"T1": 1, "T2": 2},
        verbose=False,
    )
    if not len(events):
        raise RuntimeError("No T1/T2 annotations found")

    event_names = np.where(events[:, 2] == 1, "T1", "T2")
    metadata = pd.DataFrame({
        "subject": subject,
        "run": run,
        "condition": condition,
        "label": int(condition == "execution"),
        "task_family": task_family,
        "repetition": repetition,
        "event_name": event_names,
        "movement": [movement_name(task_family, e) for e in event_names],
        "onset_seconds": events[:, 0] / raw.info["sfreq"],
        "source_file": Path(files[0]).name,
    })

    epochs = mne.Epochs(
        raw,
        events,
        event_id={"T1": 1, "T2": 2},
        tmin=CFG.epoch_tmin,
        tmax=CFG.epoch_tmax,
        baseline=None,
        preload=True,
        reject={"eeg": CFG.reject_peak_to_peak_uv * 1e-6},
        reject_by_annotation=True,
        metadata=metadata,
        event_repeated="drop",
        verbose=False,
    )
    epochs.load_data()

    log_row = {
        "subject": subject,
        "run": run,
        "condition": condition,
        "task_family": task_family,
        "n_events": len(events),
        "n_kept": len(epochs),
        "n_rejected": len(events) - len(epochs),
        "rejection_rate": 1.0 - (len(epochs) / len(events)),
        "status": "ok" if len(epochs) else "all_rejected",
        "error": "",
    }
    return epochs, log_row


