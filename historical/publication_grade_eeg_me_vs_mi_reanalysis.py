"""## Interpretable ERD features

For each retained channel, Welch power is calculated in the mu (8–13 Hz) and beta (13–30 Hz) bands. The feature is a baseline-referenced decibel ratio:

$$\mathrm{ERD/ERS}_{c,b}=10\log_{10}\left(\frac{P_{c,b}^{\mathrm{task}}+\epsilon}{P_{c,b}^{\mathrm{baseline}}+\epsilon}\right).$$

Negative values indicate task-period power reduction relative to the pre-cue rest interval; positive values indicate an increase. This produces 42 interpretable features (21 channels × 2 bands) and avoids the very high-dimensional flattened Mel representation. Feature extraction itself is label-free; the supervised selector remains inside cross-validation.

"""

BANDS = {"mu": (8.0, 13.0), "beta": (13.0, 30.0)}


def band_powers(data, sfreq, bands=BANDS):
    n_times = data.shape[-1]
    n_fft = min(256, n_times)
    psd, freqs = psd_array_welch(
        data,
        sfreq=sfreq,
        fmin=min(v[0] for v in bands.values()),
        fmax=max(v[1] for v in bands.values()),
        n_fft=n_fft,
        n_per_seg=n_fft,
        n_overlap=n_fft // 2,
        average="mean",
        verbose=False,
    )
    output = {}
    for name, (low, high) in bands.items():
        # Avoid double-counting 13 Hz in the two adjacent bands.
        mask = (freqs >= low) & (freqs < high if high < 30 else freqs <= high)
        output[name] = scipy.integrate.trapezoid(psd[..., mask], freqs[mask], axis=-1)
    return output


def extract_erd_features(epochs):
    baseline = epochs.copy().crop(CFG.baseline_tmin, CFG.baseline_tmax)
    task = epochs.copy().crop(CFG.task_tmin, CFG.task_tmax)
    baseline_power = band_powers(baseline.get_data(copy=False), epochs.info["sfreq"])
    task_power = band_powers(task.get_data(copy=False), epochs.info["sfreq"])

    feature_blocks = []
    feature_names = []
    eps = np.finfo(float).tiny
    for band in BANDS:
        feature_blocks.append(10 * np.log10((task_power[band] + eps) / (baseline_power[band] + eps)))
        feature_names.extend([f"{channel}_{band}_erd_db" for channel in epochs.ch_names])

    X = np.concatenate(feature_blocks, axis=1)
    if not np.isfinite(X).all():
        raise ValueError("Non-finite ERD features found; inspect PSD and epoch quality.")
    return X, feature_names


