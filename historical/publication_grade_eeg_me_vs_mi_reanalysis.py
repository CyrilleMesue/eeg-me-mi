"""## Nested participant-disjoint evaluation

The same participant folds are reused across models and duration analyses. The outer folds estimate performance on unseen participants. Each outer training set contains a second participant-disjoint cross-validation loop for hyperparameter selection. The held-out outer participants are not used to choose features, CSP filters, regularization, or hyperparameters.

Participant-level means and confidence intervals are primary because the scientific population consists of participants, not independent EEG segments. Epoch-pooled values are retained as secondary descriptive results.

"""

METRIC_NAMES = [
    "balanced_accuracy", "roc_auc", "macro_f1", "sensitivity",
    "specificity", "average_precision", "accuracy", "mcc",
]


def make_group_folds(groups, n_splits, seed):
    unique_groups = np.array(sorted(np.unique(groups)))
    if len(unique_groups) < n_splits:
        raise ValueError(f"Need at least {n_splits} groups; got {len(unique_groups)}")
    splitter = KFold(n_splits=n_splits, shuffle=True, random_state=seed)
    folds = []
    for train_g_idx, test_g_idx in splitter.split(unique_groups):
        train_groups = unique_groups[train_g_idx]
        test_groups = unique_groups[test_g_idx]
        train_idx = np.flatnonzero(np.isin(groups, train_groups))
        test_idx = np.flatnonzero(np.isin(groups, test_groups))
        assert set(groups[train_idx]).isdisjoint(set(groups[test_idx]))
        folds.append((train_idx, test_idx))
    return folds


def continuous_score(estimator, X):
    if hasattr(estimator, "predict_proba"):
        return estimator.predict_proba(X)[:, 1]
    if hasattr(estimator, "decision_function"):
        raw = np.asarray(estimator.decision_function(X), dtype=float)
        return 1.0 / (1.0 + np.exp(-np.clip(raw, -40, 40)))
    raise TypeError("Estimator must expose predict_proba or decision_function for ROC–AUC.")


def compute_metrics(y_true, y_pred, y_score):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "roc_auc": roc_auc_score(y_true, y_score),
        "macro_f1": f1_score(y_true, y_pred, average="macro"),
        "sensitivity": tp / (tp + fn) if (tp + fn) else np.nan,
        "specificity": tn / (tn + fp) if (tn + fp) else np.nan,
        "average_precision": average_precision_score(y_true, y_score),
        "accuracy": accuracy_score(y_true, y_pred),
        "mcc": matthews_corrcoef(y_true, y_pred),
    }


def participant_metric_table(oof):
    rows = []
    for subject, frame in oof.groupby("subject", sort=True):
        if frame["y_true"].nunique() != 2:
            continue
        rows.append({"subject": int(subject), **compute_metrics(
            frame["y_true"].to_numpy(),
            frame["y_pred"].to_numpy(),
            frame["y_score"].to_numpy(),
        )})
    return pd.DataFrame(rows)


def bootstrap_participant_means(subject_metrics, n_bootstrap, seed):
    rng = np.random.default_rng(seed)
    values = subject_metrics[METRIC_NAMES].to_numpy(dtype=float)
    boot = np.empty((n_bootstrap, values.shape[1]), dtype=float)
    for i in range(n_bootstrap):
        sample = rng.integers(0, len(values), size=len(values))
        boot[i] = np.nanmean(values[sample], axis=0)
    rows = []
    for j, metric in enumerate(METRIC_NAMES):
        rows.append({
            "metric": metric,
            "participant_mean": np.nanmean(values[:, j]),
            "ci_low": np.nanquantile(boot[:, j], 0.025),
            "ci_high": np.nanquantile(boot[:, j], 0.975),
        })
    return pd.DataFrame(rows)


def selected_feature_rows(best_estimator, feature_names, fold):
    if feature_names is None or not hasattr(best_estimator, "named_steps"):
        return []
    selector = best_estimator.named_steps.get("select")
    classifier = best_estimator.named_steps.get("classifier")
    if selector is None or classifier is None or not hasattr(selector, "get_support"):
        return []
    support = selector.get_support()
    coefs = np.ravel(classifier.coef_)
    return [
        {
            "fold": fold,
            "feature": feature,
            "coefficient": float(coef),
        }
        for feature, coef in zip(np.asarray(feature_names)[support], coefs)
    ]


def run_nested_group_cv(
    model_name,
    X,
    y,
    groups,
    metadata,
    estimator,
    param_grid,
    feature_names=None,
    verbose=True,
):
    outer_folds = make_group_folds(groups, CFG.outer_folds, CFG.seed)
    oof_rows, fold_rows, feature_rows = [], [], []

    for fold, (train_idx, test_idx) in enumerate(outer_folds, start=1):
        inner_cv = make_group_folds(
            groups[train_idx],
            min(CFG.inner_folds, len(np.unique(groups[train_idx]))),
            CFG.seed + fold,
        )
        search = GridSearchCV(
            estimator=clone(estimator),
            param_grid=param_grid,
            scoring="roc_auc",
            cv=inner_cv,
            refit=True,
            n_jobs=CFG.n_jobs,
            return_train_score=False,
            error_score="raise",
        )
        search.fit(X[train_idx], y[train_idx])
        best = search.best_estimator_
        y_score = continuous_score(best, X[test_idx])
        y_pred = best.predict(X[test_idx]).astype(int)
        fold_metric = compute_metrics(y[test_idx], y_pred, y_score)
        fold_rows.append({
            "model": model_name,
            "fold": fold,
            "n_train_subjects": len(np.unique(groups[train_idx])),
            "n_test_subjects": len(np.unique(groups[test_idx])),
            "n_train_epochs": len(train_idx),
            "n_test_epochs": len(test_idx),
            "best_inner_auc": search.best_score_,
            "best_params": json.dumps(search.best_params_, sort_keys=True),
            **fold_metric,
        })
        feature_rows.extend(selected_feature_rows(best, feature_names, fold))

        for local_i, global_i in enumerate(test_idx):
            row = metadata.iloc[global_i]
            oof_rows.append({
                "model": model_name,
                "epoch_index": int(global_i),
                "fold": fold,
                "subject": int(groups[global_i]),
                "run": int(row["run"]),
                "condition": row["condition"],
                "task_family": row["task_family"],
                "movement": row["movement"],
                "onset_seconds": float(row["onset_seconds"]),
                "y_true": int(y[global_i]),
                "y_pred": int(y_pred[local_i]),
                "y_score": float(y_score[local_i]),
            })
        if verbose:
            print(
                f"{model_name} fold {fold}/{CFG.outer_folds}: "
                f"balanced accuracy={fold_metric['balanced_accuracy']:.3f}, "
                f"AUC={fold_metric['roc_auc']:.3f}"
            )

    oof = pd.DataFrame(oof_rows).sort_values("epoch_index").reset_index(drop=True)
    folds = pd.DataFrame(fold_rows)
    subject_metrics = participant_metric_table(oof)
    summary = bootstrap_participant_means(subject_metrics, CFG.n_bootstrap, CFG.seed)
    summary.insert(0, "model", model_name)
    features = pd.DataFrame(feature_rows)
    return {
        "model": model_name,
        "oof": oof,
        "folds": folds,
        "subject_metrics": subject_metrics,
        "summary": summary,
        "selected_features": features,
    }

